#!/usr/bin/env python3
"""The Windows time zone names of an invitation, as the IANA names the reader can use.

Exchange and Outlook write `TZID:Russian Standard Time` — a name from Windows, not from IANA.
The mapping is CLDR's (`common/supplemental/windowsZones.xml`, the `territory="001"` rows, one
per Windows name), and it lands in `crates/depesha-core/src/calendar/windows_zones.rs`.

    scripts/gen-windows-zones.py                  download the file and write the table
    scripts/gen-windows-zones.py path/to.xml      the same from a copy already on disk

The table is committed: the build and the parser never touch the network. Run this only when
CLDR has moved, and commit the result with the script.
"""

import pathlib
import sys
import urllib.request
import xml.etree.ElementTree as ET

SOURCE = "https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml"
OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/depesha-core/src/calendar/windows_zones.rs"

HEAD = '''// Generated by `scripts/gen-windows-zones.py` from CLDR's `windowsZones.xml`. Do not edit by hand.
//
// Windows time zone names, as Exchange and Outlook write them in an invitation
// (`TZID:Russian Standard Time`), and the IANA name each one stands for. One row per name: the
// `territory="001"` row of CLDR, the one the standard takes for a name no country claims.
//
// The data is Copyright © 1991-2024 Unicode, Inc., used under the Unicode License v3
// (https://www.unicode.org/license.txt), and redistributed here unchanged in the two columns
// below. CLDR's `otherVersion` of the version this table was taken from: {version}.

/// The IANA name of a Windows time zone, or none when the name is not one.
///
/// The names differ in case between clients ("W. Europe Standard Time" and "W. Europe Standard
/// time"), so the search ignores case.
pub fn iana(windows: &str) -> Option<&'static str> {{
    let name = windows.trim();
    TABLE
        .iter()
        .find(|(w, _)| w.eq_ignore_ascii_case(name))
        .map(|(_, iana)| *iana)
}}

/// Windows name, IANA name: by the Windows name, as CLDR spells it.
static TABLE: &[(&str, &str)] = &[
'''

TAIL = "];\n"


def rows(xml_text):
    root = ET.fromstring(xml_text)
    zones = root.find("./windowsZones/mapTimezones")
    version = zones.get("otherVersion", "unknown")
    table = {}
    for zone in zones.findall("mapZone"):
        if zone.get("territory") != "001":
            continue
        table[zone.get("other")] = zone.get("type")
    return version, table


def rust(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    if len(sys.argv) > 1:
        xml_text = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(SOURCE, timeout=30) as answer:
            xml_text = answer.read().decode("utf-8")
    version, table = rows(xml_text)
    body = "".join(f'    ("{rust(w)}", "{rust(iana)}"),\n' for w, iana in sorted(table.items()))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEAD.format(version=version) + body + TAIL, encoding="utf-8")
    print(f"{OUT}: {len(table)} names, CLDR {version}")


if __name__ == "__main__":
    main()
