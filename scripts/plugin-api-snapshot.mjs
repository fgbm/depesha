#!/usr/bin/env node
// Snapshot of the public API of `@depesha/plugin-api`: every export with its signature, and the
// declarations of the types those signatures use, in one .d.ts (docs/plugin-api.snapshot.d.ts).
// Plugins live by this file, so a change of it is a change of the contract.
//
//   node scripts/plugin-api-snapshot.mjs           check: fails when the API differs from the snapshot
//   node scripts/plugin-api-snapshot.mjs --update  write the snapshot
//
// Only the declarations are read (no bodies, no comments): a type that a plugin cannot see does
// not change the snapshot, and one it can see - even a core type reached through MessageRow - does.
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const ENTRY = join(ROOT, "src/plugin-api/index.ts");
export const SNAPSHOT = join(ROOT, "docs/plugin-api.snapshot.d.ts");

const TYPE_LIKE = ts.SymbolFlags.Interface | ts.SymbolFlags.TypeAlias | ts.SymbolFlags.Enum | ts.SymbolFlags.Class;

/** The major version of svelte: the component types below are Svelte 5's, and a plugin is built against them. */
function svelteMajor() {
  const { dependencies = {}, devDependencies = {} } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf-8"));
  return /\d+/.exec(dependencies.svelte ?? devDependencies.svelte ?? "")?.[0] ?? "?";
}

const header = () => `// The public API of @depesha/plugin-api. Generated by scripts/plugin-api-snapshot.mjs; do not edit.
// After a deliberate change: npm run plugin-api:update, and a line in plugins/CHANGELOG.md.
// svelte major: ${svelteMajor()}
`;

/** Code-point order: the same on every machine, unlike localeCompare. */
const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function resolveAlias(checker, symbol) {
  return symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
}

function isProjectFile(file) {
  return !file.isDeclarationFile && !file.fileName.includes("/node_modules/");
}

/** The package a declaration from node_modules comes from, to import its name in the snapshot. */
function packageOf(fileName) {
  const m = /\/node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(fileName);
  return m ? m[1].replace(/^@types\//, "") : null;
}

/**
 * The text of `node` without comments, formatted by the printer (so the snapshot ignores style).
 * A type imported under another name (`import type { Row as P2 }`) is written by its own name:
 * the snapshot declares it as `Row`, and `P2` means nothing outside the file.
 */
function print(checker, printer, node, file) {
  const unalias = (context) => (root) => {
    const visit = (n) => {
      if (ts.isIdentifier(n)) {
        const symbol = checker.getSymbolAtLocation(n);
        if (symbol && symbol.flags & ts.SymbolFlags.Alias) {
          const target = checker.getAliasedSymbol(symbol);
          if (target.flags & TYPE_LIKE && target.name !== n.text) return ts.factory.createIdentifier(target.name);
        }
        return n;
      }
      return ts.visitEachChild(n, visit, context);
    };
    return ts.visitNode(root, visit);
  };
  const [changed] = ts.transform(node, [unalias]).transformed;
  return printer.printNode(ts.EmitHint.Unspecified, changed, file);
}

/** Every declaration the node mentions by name: [project type-like symbols, external type names by package]. */
function mentions(program, checker, node, found, external) {
  const visit = (n) => {
    if (ts.isIdentifier(n)) {
      const symbol = checker.getSymbolAtLocation(n);
      const target = symbol && resolveAlias(checker, symbol);
      const decl = target?.declarations?.[0];
      if (decl && target.flags & TYPE_LIKE) {
        const file = decl.getSourceFile();
        if (program.isSourceFileDefaultLibrary(file)) return;
        if (isProjectFile(file)) found.add(target);
        else {
          const pkg = packageOf(file.fileName);
          if (pkg) (external.get(pkg) ?? external.set(pkg, new Set()).get(pkg)).add(target.name);
        }
      }
    }
    ts.forEachChild(n, visit);
  };
  visit(node);
}

/** A declaration as the snapshot shows it: types whole, functions and constants without bodies. */
function declare(checker, printer, symbol, name, exported) {
  const decl = symbol.declarations[0];
  const file = decl.getSourceFile();
  const mods = exported ? "export " : "";
  const bare = (node) => print(checker, printer, node, file).replace(/^export\s+/, "").replace(/^declare\s+/, "");
  if (ts.isInterfaceDeclaration(decl) || ts.isTypeAliasDeclaration(decl) || ts.isEnumDeclaration(decl) || ts.isClassDeclaration(decl)) {
    return { text: `${mods}${bare(decl)}`, nodes: [decl] };
  }
  if (ts.isFunctionDeclaration(decl)) {
    const sig = checker.getSignatureFromDeclaration(decl);
    const node = checker.signatureToSignatureDeclaration(sig, ts.SyntaxKind.FunctionDeclaration, decl, ts.NodeBuilderFlags.NoTruncation);
    const text = print(checker, printer, ts.factory.updateFunctionDeclaration(node, undefined, undefined, ts.factory.createIdentifier(name), node.typeParameters, node.parameters, node.type, undefined), file);
    // Only what a caller sees: the parameters, the type parameters and the declared result, not the body.
    const nodes = [...decl.parameters, ...(decl.typeParameters ?? []), ...(decl.type ? [decl.type] : [])];
    return { text: `${mods}declare ${text}`, nodes };
  }
  if (ts.isVariableDeclaration(decl)) {
    const type = decl.type ?? checker.typeToTypeNode(checker.getTypeAtLocation(decl), decl, ts.NodeBuilderFlags.NoTruncation);
    return { text: `${mods}declare const ${name}: ${print(checker, printer, type, file)};`, nodes: decl.type ? [decl.type] : [] };
  }
  throw new Error(`plugin-api: cannot describe the export «${name}» (${ts.SyntaxKind[decl.kind]})`);
}

/** The snapshot of the module at `entry`. */
export function buildSnapshot(entry = ENTRY) {
  const program = ts.createProgram([entry], {
    target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    strict: true,
    skipLibCheck: true,
    noEmit: true,
    types: [],
  });
  const checker = program.getTypeChecker();
  const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });
  const module = checker.getSymbolAtLocation(program.getSourceFile(entry));
  if (!module) throw new Error(`${entry} is not a module`);

  const out = [];
  const found = new Set();
  const external = new Map();
  const taken = new Map();
  const where = (symbol) => relative(ROOT, symbol.declarations[0].getSourceFile().fileName);
  /** Whether `symbol` is new; a different symbol under a taken name cannot share the snapshot. */
  const claim = (symbol, name) => {
    const prev = taken.get(name);
    if (prev && prev !== symbol) {
      throw new Error(`В API плагинов два разных «${name}»: ${where(prev)} и ${where(symbol)}. В снимке имя одно — переименуй один из типов.`);
    }
    taken.set(name, symbol);
    return !prev;
  };
  const add = (symbol, name, exported) => {
    claim(symbol, name);
    const { text, nodes } = declare(checker, printer, symbol, name, exported);
    out.push({ name, exported, text });
    for (const n of nodes) mentions(program, checker, n, found, external);
  };

  const exports = checker.getExportsOfModule(module).sort((a, b) => byName(a.name, b.name));
  for (const e of exports) add(resolveAlias(checker, e), e.name, true);
  // The types the exports use but do not export: a plugin sees their shape through a field.
  const queue = [...found];
  for (const symbol of queue) {
    if (!claim(symbol, symbol.name)) continue;
    add(symbol, symbol.name, false);
    for (const s of found) if (!queue.includes(s)) queue.push(s);
  }

  const imports = [...external]
    .sort(([a], [b]) => byName(a, b))
    .map(([pkg, names]) => `import type { ${[...names].sort().join(", ")} } from "${pkg}";`);
  const rank = (d) => (d.exported ? 0 : 1);
  const body = out.sort((a, b) => rank(a) - rank(b) || byName(a.name, b.name)).map((d) => d.text);
  return `${[header().trimEnd(), imports.join("\n"), ...body].filter(Boolean).join("\n\n")}\n`;
}

/** The message of a failed check, or null when the API is as the snapshot says. */
export function checkSnapshot(entry = ENTRY, snapshot = SNAPSHOT) {
  const now = buildSnapshot(entry);
  const was = existsSync(snapshot) ? readFileSync(snapshot, "utf-8") : "";
  if (now === was) return null;
  const dir = mkdtempSync(join(tmpdir(), "plugin-api-"));
  try {
    writeFileSync(join(dir, "now.d.ts"), now);
    const diff = spawnSync("diff", ["-u", "--label", "снимок", "--label", "сейчас", snapshot, join(dir, "now.d.ts")], { encoding: "utf-8" });
    return `API плагинов изменился: обнови снимок командой «npm run plugin-api:update» и отметь изменение в plugins/CHANGELOG.md.\n${diff.stdout ?? ""}`;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--update")) {
    writeFileSync(SNAPSHOT, buildSnapshot());
    console.log(`Снимок записан: ${relative(ROOT, SNAPSHOT)}. Отметь изменение в plugins/CHANGELOG.md.`);
  } else {
    const failure = checkSnapshot();
    if (failure) {
      console.error(failure);
      process.exit(1);
    }
    console.log("API плагинов совпадает со снимком.");
  }
}
